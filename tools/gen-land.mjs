// Build-time generator for the globe's land dot matrix.
// Samples a latitude-row grid, keeps the points that fall on land (world-atlas 110m)
// and writes them as a compact base64 Int16 array (lat*100, lon*100 pairs) to
// src/globe/land-dots.gen.ts so the browser never does point-in-polygon work.
import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'src/globe/land-dots.gen.ts');
const STEP = 1.05; // degrees between rows / dots

// Skip the (slow, ~20s) regeneration when the committed output is up to date.
const self = fileURLToPath(import.meta.url);
if (!process.argv.includes('--force') && existsSync(out) && statSync(out).mtimeMs >= statSync(self).mtimeMs) {
  console.log('[gen-land] land-dots.gen.ts is up to date (use --force to regenerate)');
  process.exit(0);
}

const require = createRequire(import.meta.url);
let topo;
try {
  topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
} catch {
  if (existsSync(out)) {
    console.log('[gen-land] world-atlas not installed, keeping committed land-dots.gen.ts');
    process.exit(0);
  }
  throw new Error('world-atlas is required to generate land dots');
}
const land = feature(topo, topo.objects.land);

const pts = [];
for (let lat = -84; lat <= 84; lat += STEP) {
  const step = STEP / Math.max(0.12, Math.cos((lat * Math.PI) / 180));
  // offset every other row a little so the matrix doesn't look like vertical stripes
  const phase = (Math.round(lat / STEP) % 2) * step * 0.5;
  for (let lon = -180 + phase; lon < 180; lon += step) {
    if (geoContains(land, [lon, lat])) pts.push(Math.round(lat * 100), Math.round(lon * 100));
  }
}
const buf = Buffer.from(new Int16Array(pts).buffer);
const src =
  '// AUTO-GENERATED by tools/gen-land.mjs — do not edit.\n' +
  `// ${pts.length / 2} land dots, Int16 pairs (lat*100, lon*100), little-endian, base64.\n` +
  `export const LAND_DOT_COUNT = ${pts.length / 2};\n` +
  `export const LAND_DOTS_B64 =\n  '${buf.toString('base64')}';\n`;
writeFileSync(out, src);
console.log(`[gen-land] wrote ${pts.length / 2} land dots`);
